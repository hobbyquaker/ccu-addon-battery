// Package addonpkg tests the package files the addon ships: the manifest as the system would
// validate it at install, and the lighttpd fragment `ccu-addon-kit vendor` writes from kit.json.
package addonpkg

import (
	"encoding/json"
	"os"
	"os/exec"
	"path"
	"regexp"
	"strings"
	"testing"

	"github.com/hobbyquaker/ccu-addon-kit/go/addonkit/fragment"
	"github.com/hobbyquaker/ccu-addon-kit/go/addonkit/manifest"
)

// Port is the loopback port the daemon listens on and the fragment proxies to.
const Port = 8291

func TestManifest(t *testing.T) {
	m, err := manifest.Load("../../addon/openccu-lite.json")
	if err != nil {
		t.Fatal(err)
	}
	if m.ID != "battery" || !m.UI.SessionHeader || m.Undeclared() || !m.Runtime.Daemon {
		t.Fatalf("manifest: %+v", m)
	}
	for _, want := range []string{"rpc:read", "meta:read"} {
		if !strings.Contains(strings.Join(m.Runtime.APIScopes, ","), want) {
			t.Errorf("scope %s missing", want)
		}
	}
	if m.Description["de"] == "" || m.Description["en"] == "" || m.Runtime.Note["de"] == "" || m.Runtime.Note["en"] == "" {
		t.Error("texts in both languages")
	}
}

// The fragment is the kit CLI's output (kit.json: proxied /addons/battery/ to the port, the
// settings page in its own directory /addons/battery-config/). The kit's Go renderer writes the
// same shape byte for byte (ccu-addon-kit task 18), so the shipped file must equal it, the
// header line's kit version aside.
func TestFragment(t *testing.T) {
	got, err := os.ReadFile("../../addon/battery/etc/lighttpd.conf")
	if err != nil {
		t.Fatal(err)
	}
	head, body, _ := strings.Cut(string(got), "\n")
	version := regexp.MustCompile(`generated by ccu-addon-kit (\S+) `).FindStringSubmatch(head)
	if version == nil {
		t.Fatalf("header line: %q", head)
	}
	ref, err := fragment.Render(fragment.Fragment{ID: "battery", Path: "/addons/battery/", WWW: "battery-config", Port: Port,
		ErrorfilePrefix: "/usr/local/addons/battery/www/lighttpd-error-", KitVersion: version[1]})
	if err != nil {
		t.Fatal(err)
	}
	if ref != string(got) {
		t.Errorf("the shipped fragment differs from the Go renderer's:\n%s\n--- want ---\n%s", got, ref)
	}
	for _, want := range []string{
		`$HTTP["url"] == "/addons/battery" {`,
		`url.redirect = ("" => "/addons/battery/")`,
		`("host" => "127.0.0.1", "port" => 8291)`,
		`server.errorfile-prefix = "/usr/local/addons/battery/www/lighttpd-error-"`,
	} {
		if !strings.Contains(body, want) {
			t.Errorf("the shipped fragment lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(string(got), "battery-config") {
		t.Error("the fragment must not touch /addons/battery-config/ (the web server serves it)")
	}
}

func TestScriptsAreExecutable(t *testing.T) {
	for _, f := range []string{"../../addon/update_script", "../../addon/battery/rc.d"} {
		st, err := os.Stat(f)
		if err != nil {
			t.Fatal(err)
		}
		if st.Mode()&0o111 == 0 {
			t.Errorf("%s is not executable", f)
		}
		b, _ := os.ReadFile(f)
		if strings.Contains(string(b), "\r") {
			t.Errorf("%s has CR line endings", f)
		}
	}
}

// B-2: the name the rc.d script's info gives is what openccu-lite's menu and Addons page show
// (one string for both languages): the German one, as the settings page (kit.json) and the CCU's
// button (battery.cfg) name the addon.
func TestInfoName(t *testing.T) {
	b, err := os.ReadFile("../../addon/battery/rc.d")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "\nNAME=\"Batterie\"\n") {
		t.Error(`rc.d: NAME="Batterie" expected`)
	}
	cfg, _ := os.ReadFile("../../addon/battery.cfg")
	if !strings.Contains(string(cfg), "CONFIG_NAME Batterie") {
		t.Error("battery.cfg: CONFIG_NAME Batterie expected")
	}
}

// B-2: every file the app's page names next to itself (the favicon) is in the build: vite copies
// ui/public/ into the app; a missing one is answered with the page by the daemon's fallback.
func TestAppIcon(t *testing.T) {
	page, err := os.ReadFile("../../ui/index.html")
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`<link rel="icon" href="\./([^"]+)"`).FindStringSubmatch(string(page))
	if m == nil {
		t.Fatal("ui/index.html names no icon")
	}
	icon, err := os.ReadFile("../../ui/public/" + m[1])
	if err != nil {
		t.Fatalf("the app's icon %s is not in ui/public: %v", m[1], err)
	}
	if !strings.HasPrefix(string(icon), "<svg") {
		t.Errorf("%s is not an SVG", m[1])
	}
}

// B-6: the system's catalogue check reads the manifest's images from the repository at the release
// tag, beside the manifest (the manifest's directory is taken as the package root), and the install
// reads them from the package at the same paths. So every declared image must be a file the
// repository tracks at that path - not one the build copies in from elsewhere.
func TestManifestImagesAreInTheRepository(t *testing.T) {
	b, err := os.ReadFile("../../addon/openccu-lite.json")
	if err != nil {
		t.Fatal(err)
	}
	var m struct {
		UI map[string]any `json:"ui"`
	}
	if err := json.Unmarshal(b, &m); err != nil {
		t.Fatal(err)
	}
	n := 0
	for _, key := range []string{"icon", "icon_dark", "logo", "logo_dark"} {
		v, ok := m.UI[key]
		if !ok {
			continue
		}
		p, _ := v.(string)
		if p == "" || path.IsAbs(p) || strings.Contains(p, "..") {
			t.Errorf("ui.%s: %q is not a path relative to the package root", key, v)
			continue
		}
		n++
		rel := "addon/" + p
		out, err := exec.Command("git", "-C", "../..", "ls-files", "--error-unmatch", "--", rel).CombinedOutput()
		if err != nil {
			t.Errorf("ui.%s: %s is not tracked in the repository (the catalogue would answer 404): %v %s", key, rel, err, out)
			continue
		}
		img, err := os.ReadFile("../../" + rel)
		if err != nil {
			t.Errorf("ui.%s: %v", key, err)
			continue
		}
		if len(img) > 256<<10 || !strings.Contains(string(img[:min(len(img), 512)]), "<svg") {
			t.Errorf("ui.%s: %s is not an SVG of at most 256 KiB", key, rel)
		}
	}
	if n == 0 {
		t.Error("the manifest declares no image")
	}
}
